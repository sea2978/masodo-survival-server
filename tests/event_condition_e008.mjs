import assert from "node:assert/strict";
import { createServerPlayer } from "../src/game_data.js";
import { ENCOUNTER_EVENTS } from "../src/offline_content.js";
import { eventChoiceAvailability, initWorld, resolveEventChoice } from "../src/match_engine.js";
const t0=1_700_230_000_000;
const p=createServerPlayer({sessionId:"c2",playerName:"C2",charId:"c01",startRegion:"estate"},0);
const match={matchId:"c2",phase:"playing",createdAt:t0,startedAt:t0,updatedAt:t0,players:[p],eventPity:{},lastEventId:null,corpses:[],worldLog:[]};
initWorld(match);
const e=ENCOUNTER_EVENTS.find(x=>x.id==="E008");
assert.ok(e);
assert.equal(eventChoiceAvailability(e,p,1).available,false);
p.mat.precision=1;
assert.equal(eventChoiceAvailability(e,p,1).available,true);
p.pendingEvent="E008";
const oldRandom=Math.random;Math.random=()=>0.5;
const result=resolveEventChoice(match,p,1,t0+1000);
Math.random=oldRandom;
assert.equal(result.ok,true);
assert.equal(p.mat.precision||0,0);
console.log("E008 condition/cost ok",result.summary);
